import type { Asset, QuarterlyEarnings, Exchange, Currency } from '@/types';

// Deterministic pseudo-random generator so chart sparklines are stable across renders
function seeded(seed: number) {
  let s = seed % 2147483647;
  if (s <= 0) s += 2147483646;
  return () => {
    s = (s * 16807) % 2147483647;
    return (s - 1) / 2147483646;
  };
}

function sparkline(seed: number, start: number, drift: number): number[] {
  const rand = seeded(seed);
  const pts: number[] = [];
  let v = start;
  for (let i = 0; i < 24; i++) {
    v += (rand() - 0.5) * start * 0.01 + drift / 24;
    pts.push(Number(v.toFixed(2)));
  }
  return pts;
}

const QUARTERS = ['Q3 2026', 'Q2 2026', 'Q1 2026', 'Q4 2025'];

function earnings(
  seed: number,
  epsBase: number,
  revBase: number,
  beat: boolean[],
): QuarterlyEarnings[] {
  const rand = seeded(seed);
  return QUARTERS.map((quarter, i) => {
    const surprise = (rand() - 0.5) * 0.2;
    const epsEstimate = Number((epsBase * (1 + (i - 1.5) * 0.05)).toFixed(2));
    const epsActual = beat[i]
      ? Number((epsEstimate * (1 + Math.abs(surprise) + 0.03)).toFixed(2))
      : Number((epsEstimate * (1 - Math.abs(surprise) * 0.5)).toFixed(2));
    const revEstimate = Number((revBase * (1 + (i - 1.5) * 0.04)).toFixed(0));
    const revActual = beat[i]
      ? Number((revEstimate * (1 + Math.abs(surprise) * 0.5 + 0.02)).toFixed(0))
      : Number((revEstimate * (1 - Math.abs(surprise) * 0.3)).toFixed(0));
    return { quarter, epsActual, epsEstimate, revenueActual: revActual, revenueEstimate: revEstimate };
  });
}

type RawAsset = Omit<Asset, 'exchange' | 'currency'> & { exchange?: Exchange; currency?: Currency };

function makeAsset(raw: RawAsset): Asset {
  return {
    ...raw,
    exchange: raw.exchange ?? 'NASDAQ',
    currency: raw.currency ?? 'USD',
  };
}

